-- Question 1
-- Retrieve employee names and their manager names
-- (Self Join using aliases)
-- ==========================================================

CREATE TABLE EMPLOYEES (
    EMPLOYEE_ID NUMBER PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(50),
    MANAGER_ID NUMBER
);

