INSERT INTO EMPLOYEES VALUES (2,'Sara',1);
INSERT INTO EMPLOYEES VALUES (3,'Ali',1);

SELECT E.EMPLOYEE_NAME AS EMPLOYEE,
       M.EMPLOYEE_NAME AS MANAGER
FROM EMPLOYEES E
LEFT JOIN EMPLOYEES M
ON E.MANAGER_ID = M.EMPLOYEE_ID;


